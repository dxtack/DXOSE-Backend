function normalizeRoleCode(role = '') {
    const normalized = String(role).toUpperCase();
    return normalized === 'SECURITY_MANAGER' ? 'SECURITY' : normalized;
}

function mergeAuthorityGrants(base = BASE_ROLE_PERMISSIONS) {
    const merged = {};
    for (const [role, codes] of Object.entries(base)) {
        merged[role] = [...codes];
    }
    for (const [permCode, roleMap] of Object.entries(AUTHORITY_ROLE_GRANTS)) {
        for (const [role, enabled] of Object.entries(roleMap)) {
            if (!enabled) continue;
            if (!merged[role]) merged[role] = [];
            if (!merged[role].includes(permCode)) merged[role].push(permCode);
        }
    }
    return merged;
}

const DEPT_MANAGER_STRIPPED_SET = new Set(DEPT_MANAGER_STRIPPED_PERMISSIONS);

/** Safety net when reading ur_* / legacy rows that still contain stripped codes. */
function applyRolePermissionPolicy(roleCode, permissionCodes) {
    if (normalizeRoleCode(roleCode) !== 'DEPT_MANAGER') {
        return permissionCodes;
    }
    return (permissionCodes || []).filter((code) => !DEPT_MANAGER_STRIPPED_SET.has(code));
}

function buildRolePermissionMap() {
    return mergeAuthorityGrants(BASE_ROLE_PERMISSIONS);
}

